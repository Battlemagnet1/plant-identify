package com.plantidentify

/**
 * 当前构建是哪个版本。
 *
 * 两个版本共用同一份代码、同一个数据库结构、同一套 AI 请求 ——
 * 差别只在**界面入口**：
 *
 * | 功能 | base | full |
 * |---|---|---|
 * | 多图识别 · 文字分析 · 档案 · 搜索筛选 · 归并 · 备注 | ✅ | ✅ |
 * | 统计页 | — | ✅ |
 * | 观察地点（权限 + 地点行 + 详情/观察页展示） | — | ✅ |
 * | HTML 导出 / 备份 / 恢复（数据管理页） | — | ✅ |
 * | 常用名称（俗称）与病虫害防治 | — | ✅ |
 * | 大图查看与保存到相册 | — | ✅ |
 * | 编辑页的照片增删 | — | ✅ |
 *
 * 所以判断一律写在**入口处**（「这个按钮显不显示」「这一页进不进得去」），
 * 不要散进业务逻辑里。散进去的后果是：同一份逻辑在 base 上走出不同的分支，
 * 而两个包的数据本应完全互通 —— 那样一来备份包互相迁移就会出问题。
 */
object AppEdition {

    /** 是否为完整版。编译期常量，R8 之外也不会留下运行期分支开销。 */
    const val isFull: Boolean = BuildConfig.FULL_EDITION

    /**
     * 只在完整版存在的功能。
     *
     * 写成一个具名判断而不是到处写 `AppEdition.isFull`，
     * 是为了让「这里为什么要有条件」在调用处就能读出来 ——
     * 否则几个月后会有人把它当成多余的开关删掉。
     */
    inline fun ifFull(block: () -> Unit) {
        if (isFull) block()
    }
}
