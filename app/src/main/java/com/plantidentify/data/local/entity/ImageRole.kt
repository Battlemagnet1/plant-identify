package com.plantidentify.data.local.entity

/**
 * 照片在一次观察中扮演的角色（即拍摄部位）。
 *
 * 为什么需要这个字段：
 * 本应用的核心卖点是「多图联合识别」——把同一株植物的多张照片当作不同观察角度综合判断。
 * 但实验证据显示，视觉模型在多图输入时容易退化成「逐图独立描述」，
 * 一个重要原因是模型需要自己猜「哪张图该看什么部位」。
 *
 * 由用户显式标注部位后，prompt 中可以写成「照片2 是叶片特写，重点观察叶形与叶序」，
 * 从而把一个需要跨图推理的任务拆解为多个单图子任务，绕开模型短板。
 *
 * UI 上默认为 [UNKNOWN]，不强制用户标注，不增加使用负担。
 */
enum class ImageRole {
    /** 未标注（默认） */
    UNKNOWN,

    /** 整体植株：观察株型、树姿 */
    WHOLE_PLANT,

    /** 叶片：观察叶形、叶缘、叶序、叶脉 */
    LEAF,

    /** 花：观察花序、花冠、花色 */
    FLOWER,

    /** 果实 / 种子 */
    FRUIT,

    /** 茎干 / 树皮：木本植物建议提供 */
    BARK,

    /** 生境 / 群落环境（用于调查记录，不直接用于物种识别） */
    HABITAT,
    ;

    /** 是否直接参与物种识别（生境照片对鉴定帮助有限） */
    val contributesToIdentification: Boolean
        get() = this != UNKNOWN && this != HABITAT
}
